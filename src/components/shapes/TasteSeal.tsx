"use client";

import { useMemo } from "react";

import { roleColour } from "@/lib/design/colourRoles";
import { createRandom, polarPoint } from "@/lib/utils/deterministic";

/**
 * The deterministic taste seal — a creator's identity mark.
 *
 * Extracted from chart F (`TasteFingerprint`) so that the same mark can sit in a
 * page header, on a media kit and inside the fingerprint chart without three
 * implementations drifting apart. Doc 05 §10F's requirement is that two creators
 * with different data cannot receive the same graphic; that guarantee is only
 * worth anything if every copy of the mark is generated by the same code from the
 * same signature.
 *
 * It is an IDENTITY MARK, not a measurement, and it is labelled as one wherever
 * it appears. Nothing in the geometry encodes a quantity: sector angles are a
 * fixed grid and only tick presence and length come from the hash. That is why it
 * is safe to render at 48px next to a name — a chart shrunk to 48px would be
 * unreadable, while a mark at 48px is exactly what a mark is for.
 *
 * Purely random positions would produce visual noise; a fixed angular grid with
 * randomised presence produces something that reads as a coherent mark and still
 * differs between profiles. That distinction matters because an identity graphic
 * that looks like static will not be recognised as belonging to anyone.
 */

const SEAL_SIZE = 132;
const SEAL_SECTORS = 48;
const SEAL_INNER = 34;
const SEAL_OUTER = 58;
/** Fraction of sectors left empty, so the ring has rhythm rather than being solid. */
const PRESENCE_THRESHOLD = 0.4;

export interface TasteSealProps {
  /** The profile hash. `TasteFingerprintViewModel.signature`. */
  signature: string;
  /** Rendered pixel size. Geometry is unchanged — only the box scales. */
  size?: number;
  /** Show the short hash beneath the mark. Off for tight layouts. */
  showHash?: boolean;
  className?: string;
}

export function TasteSeal({
  signature,
  size = SEAL_SIZE,
  showHash = true,
  className,
}: TasteSealProps) {
  const ticks = useMemo(() => buildTicks(signature), [signature]);

  return (
    <div
      className={`cd-print__seal${showHash ? "" : " cd-print__seal--bare"}${
        className ? ` ${className}` : ""
      }`}
      style={{ inlineSize: size }}
    >
      <svg
        viewBox={`0 0 ${SEAL_SIZE} ${SEAL_SIZE}`}
        className="cd-print__seal-svg"
        aria-hidden="true"
        focusable="false"
      >
        <circle
          cx={SEAL_SIZE / 2}
          cy={SEAL_SIZE / 2}
          r={SEAL_OUTER + 4}
          fill="none"
          stroke="rgb(var(--chart-grid))"
          opacity={0.35}
        />
        {ticks.map((tick) => (
          <line
            key={tick.key}
            x1={tick.x1}
            y1={tick.y1}
            x2={tick.x2}
            y2={tick.y2}
            stroke={roleColour("taste")}
            strokeWidth={2}
            strokeLinecap="round"
            opacity={0.55}
          />
        ))}
        <circle
          cx={SEAL_SIZE / 2}
          cy={SEAL_SIZE / 2}
          r={SEAL_INNER - 6}
          fill={roleColour("taste")}
          opacity={0.14}
        />
      </svg>

      {showHash ? (
        <code className="cd-print__hash" title="Hash of this profile">
          {shortSealHash(signature)}
        </code>
      ) : null}

      {/* Present even when the hash is hidden, so a screen-reader user is told
          directly that this is not data. Without it the mark is simply absent
          from the accessible tree, which leaves "what was that?" unanswered. */}
      <span className="cd-sr-only">
        A decorative identity pattern generated from this profile. It does not encode any value.
      </span>
    </div>
  );
}

interface Tick {
  key: number;
  x1: number;
  y1: number;
  x2: number;
  y2: number;
}

function buildTicks(signature: string): Tick[] {
  if (signature === "") return [];
  const random = createRandom(signature);
  const centre = SEAL_SIZE / 2;

  const ticks: Tick[] = [];
  for (let index = 0; index < SEAL_SECTORS; index += 1) {
    const presence = random();
    const length = random();
    if (presence < PRESENCE_THRESHOLD) continue;

    const angle = (Math.PI * 2 * index) / SEAL_SECTORS - Math.PI / 2;
    const inner = SEAL_INNER + Math.floor(length * 3) * 4;
    const outer = Math.min(SEAL_OUTER, inner + 4 + length * 8);
    // Through `polarPoint`, never raw `Math.sin`/`Math.cos`: this runs on the
    // server and again during hydration, and the two V8 builds do not agree on
    // the last ULP of a sine. See `deterministic.ts`. This seal is where that
    // divergence was first caught, taking the whole homepage with it.
    const start = polarPoint(centre, centre, inner, angle);
    const end = polarPoint(centre, centre, outer, angle);
    ticks.push({
      key: index,
      x1: start.x,
      y1: start.y,
      x2: end.x,
      y2: end.y,
    });
  }
  return ticks;
}

/**
 * The short form of a signature, for display next to the mark.
 *
 * Exported because chart F quotes the same value in its footnote, and a footnote
 * that showed a different prefix than the mark it describes would look like two
 * unrelated hashes.
 */
export function shortSealHash(signature: string): string {
  return signature === "" ? "—" : signature.slice(0, 10);
}
